"""
Сценарий для высокопроизводительного рендеринга орбит с использованием GPU.

Этот скрипт загружает предварительно рассчитанные данные о траекториях планет
и использует специализированную функцию `render_orbits_nvenc` для создания
видеофайла в формате MP4.

Ключевые особенности:
- Использует данные из папки 'data_bin_60000'.
- Отображает орбиты планет внутренней Солнечной системы (до Марса).
- Все параметры рендеринга (FPS, скорость, эффекты следа, цвета)
  жестко заданы для получения конкретного визуального стиля.
"""
from utils import load_data_binary
from visualizer_gpu import render_orbits_nvenc

# 1. Загрузка данных симуляции
# Используется набор данных с большим количеством шагов для плавности.
planets = load_data_binary("./assets/data_bin_60000")

# 2. Фильтрация и выбор планет для рендеринга
# Оставляем только основные планеты и Солнце
planets_to_render = [p for p in planets if p.name in (
    "Sun", "Mercury", "Venus", "Earth", "Mars", "Jupiter",
    "Saturn", "Uranus", "Neptune"
)]
# Ограничиваемся внутренней системой для лучшей детализации
inner_system = planets_to_render[:5]  # Солнце, Меркурий, Венера, Земля, Марс

# 3. Запуск GPU-рендеринга с заданными параметрами
render_orbits_nvenc(
    planets=inner_system,
    filename="./assets/mercury.mp4",
    fps=120,                          # Высокая частота кадров для плавности
    days_per_frame=3650 * 2,          # Количество дней симуляции, обрабатываемых за один кадр видео

    # Параметры "следа" от планет (трейла)
    trail_half_life_seconds=1.0,      # Время в секундах, за которое яркость следа уменьшится вдвое
    trail_blend="max",                # Режим наложения: 'max' дает четкий след без "взрыва" яркости

    # Параметры линий и точек
    line_alpha=0.03,                  # Прозрачность линии орбиты (делает ее тонкой и слабой)
    line_width=0.1,                   # Толщина линии орбиты
    point_alpha=1.0,                  # Непрозрачная точка самой планеты
    point_size=1.5,                   # Размер точки планеты

    # Параметры свечения (гало)
    halo_alpha=0.35,                  # Прозрачность гало вокруг планеты
    halo_size=10.0,                   # Размер гало
)