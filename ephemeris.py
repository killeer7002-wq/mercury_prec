"""
Этот модуль предоставляет функции для преобразования кеплеровых орбитальных 
элементов в векторы состояния (положение и скорость) и для получения 
этих векторов для планет Солнечной системы на эпоху J2000.
"""

import numpy as np

# Гравитационный параметр Солнца (m^3/s^2)
GM = 1.32712440018e20 

def get_state_from_kepler(a_au, e, i_deg, w_deg, Omega_deg, M_deg):
    """Преобразует кеплеровы элементы в декартовы векторы положения и скорости.

    Процесс преобразования включает три основных шага:
    1. Решение уравнения Кеплера для нахождения эксцентрической аномалии (E)
       из средней аномалии (M) с использованием метода Ньютона-Рафсона.
    2. Вычисление положения и скорости тела в плоскости его орбиты.
    3. Поворот векторов из орбитальной плоскости в эклиптическую
       систему координат с помощью матриц поворота.

    Args:
        a_au (float): Большая полуось в астрономических единицах (А.Е.).
        e (float): Эксцентриситет орбиты.
        i_deg (float): Наклонение орбиты в градусах.
        w_deg (float): Аргумент перицентра в градусах.
        Omega_deg (float): Долгота восходящего узла в градусах.
        M_deg (float): Средняя аномалия в градусах.

    Returns:
        tuple[np.ndarray, np.ndarray]: Кортеж из двух NumPy массивов:
        - r_vec: Вектор положения в 3D пространстве [x, y, z] в метрах.
        - v_vec: Вектор скорости в 3D пространстве [vx, vy, vz] в м/с.
    """
    
    AU = 1.496e11
    a = a_au * AU  # Большая полуось в метрах
    
    # Перевод угловых величин из градусов в радианы
    i = np.radians(i_deg)
    w = np.radians(w_deg)
    O = np.radians(Omega_deg)
    M = np.radians(M_deg)
    
    # 1. Решение уравнения Кеплера для эксцентрической аномалии (E)
    # Используется итерационный метод Ньютона-Рафсона.
    E = M  # Начальное приближение
    for _ in range(10): # Обычно достаточно нескольких итераций
        dE = (E - e * np.sin(E) - M) / (1 - e * np.cos(E))
        E -= dE
        if abs(dE) < 1e-9: 
            break
            
    # 2. Вычисление координат и скорости в орбитальной плоскости
    cosE = np.cos(E)
    sinE = np.sin(E)
    
    # Положение в плоскости орбиты
    x_orb = a * (cosE - e)
    y_orb = a * np.sqrt(1 - e**2) * sinE
    
    # Среднее движение (угловая скорость)
    n = np.sqrt(GM / a**3)
    # Расстояние от центрального тела
    r_mag = a * (1 - e * cosE)
    
    # Скорость в плоскости орбиты
    vx_orb = - (n * a**2 / r_mag) * sinE
    vy_orb =   (n * a**2 * np.sqrt(1 - e**2) / r_mag) * cosE
    
    # 3. Преобразование координат в эклиптическую систему
    # Векторы положения и скорости поворачиваются последовательно:
    # - на аргумент перицентра (w)
    # - на наклонение (i)
    # - на долготу восходящего узла (O)
    # Полная матрица поворота: R = R_O * R_i * R_w
    
    def rotate(x, y, vx, vy):
        """Вспомогательная функция для выполнения 3D поворота векторов."""
        pos = np.array([x, y, 0.0])
        vel = np.array([vx, vy, 0.0])
        
        # Матрица поворота вокруг оси Z на угол w (аргумент перицентра)
        R_w = np.array([
            [np.cos(w), -np.sin(w), 0],
            [np.sin(w),  np.cos(w), 0],
            [0,          0,         1]
        ])
        
        # Матрица поворота вокруг оси X на угол i (наклонение)
        R_i = np.array([
            [1, 0,          0],
            [0, np.cos(i), -np.sin(i)],
            [0, np.sin(i),  np.cos(i)]
        ])
        
        # Матрица поворота вокруг оси Z на угол O (долгота восходящего узла)
        R_O = np.array([
            [np.cos(O), -np.sin(O), 0],
            [np.sin(O),  np.cos(O), 0],
            [0,          0,         1]
        ])
        
        R = R_O @ R_i @ R_w
        
        return R @ pos, R @ vel

    r_vec, v_vec = rotate(x_orb, y_orb, vx_orb, vy_orb)
    
    return r_vec, v_vec

def get_j2000_state(name):
    """Возвращает векторы положения и скорости для планеты на эпоху J2000.

    Данные об орбитальных элементах взяты из базы данных NASA JPL Solar System Dynamics.
    Эпоха: J2000 (1 января 2000 г., 12:00 TT).
    
    Элементы в таблице data:
    - a: Большая полуось (А.Е.)
    - e: Эксцентриситет
    - i: Наклонение (градусы)
    - w: Аргумент перицентра (градусы)
    - Omega: Долгота восходящего узла (градусы)
    - M: Средняя аномалия (градусы)

    Args:
        name (str): Название планеты на английском языке (например, "Mercury").

    Returns:
        tuple[np.ndarray, np.ndarray]: Кортеж с векторами положения и скорости.

    Raises:
        ValueError: Если для указанного имени планеты нет данных.
    """
    data = {
        "Mercury": (0.387098, 0.205630, 7.005,  29.124, 48.331, 174.796),
        "Venus":   (0.723332, 0.006772, 3.394,  54.884, 76.680, 50.115),
        # Для Земли долгота восходящего узла (Omega) не определена, используется 0.
        "Earth":   (1.000000, 0.016708, 0.000,  102.937, 0.0,    357.517), 
        "Mars":    (1.523679, 0.093400, 1.850,  286.502, 49.558, 19.412),
        "Jupiter": (5.204267, 0.048498, 1.303,  273.867, 100.464, 20.020),
        "Saturn":  (9.582017, 0.055546, 2.485,  339.392, 113.665, 317.020),
        "Uranus":  (19.229411, 0.046381, 0.773, 96.9988, 74.006, 142.2386),
        "Neptune": (30.103661, 0.009456, 1.770, 276.336, 131.784, 256.228)
    }
    
    if name not in data:
        raise ValueError(f"No data for {name}")
        
    params = data[name]
    return get_state_from_kepler(*params)
